/**
 * E20-R response classifier: a fixed, deterministic label for one homepage
 * response. Protocol: docs/research/prereg/E20R-front-door-replication.md § 4.2.
 * The signature list is frozen at registration; a change after that is a
 * deviation. No model decides a label (AGENTS.md rule 4).
 *
 *   challenge     an edge network tests the client
 *   block         an edge network or firewall refuses the client
 *   origin-error  the site itself answers with an error
 *   page          a normal page
 *
 * Header markers come first: Cloudflare documents that the status code alone
 * does not identify a challenge.
 */
import { createHash } from "node:crypto";

export const CHALLENGE_HEADERS = Object.freeze([
  ["cf-mitigated", /challenge/i, "cloudflare"],
  ["x-amzn-waf-action", /challenge|captcha/i, "aws-waf"],
  ["x-vercel-mitigated", /challenge/i, "vercel"],
]);
export const CHALLENGE_BODIES = Object.freeze([
  [/\/cdn-cgi\/challenge-platform\/|<title>\s*Just a moment\.\.\.\s*<\/title>|cf-browser-verification|cf_chl_opt/i, "cloudflare"],
  [/captcha-delivery\.com/i, "datadome"],
  [/px-captcha|captcha\.px-cdn\.net/i, "human"],
  [/_Incapsula_Resource/i, "imperva"],
  [/_sec\/verify\?provider=|sec-if-cpt-container/i, "akamai"],
  [/Vercel Security Checkpoint/i, "vercel"],
  [/AwsWafIntegration|awswaf\.com/i, "aws-waf"],
]);
export const BLOCK_BODIES = Object.freeze([
  [/Attention Required! \| Cloudflare|Sorry, you have been blocked|cf-error-details/i, "cloudflare"],
  [/errors\.edgesuite\.net|<H1>Access Denied<\/H1>/i, "akamai"],
  [/Generated by cloudfront \(CloudFront\)|The request could not be satisfied/i, "cloudfront"],
  [/Incapsula incident ID/i, "imperva"],
]);
// Header values kept verbatim. Every other header keeps its name only.
export const KEPT_VALUES = Object.freeze(["cf-mitigated", "x-amzn-waf-action", "x-vercel-mitigated", "server", "via", "x-cache", "cf-cache-status"]);
export const EXCERPT_BYTES = 4096;

const lower = (headers = {}) => Object.fromEntries(Object.entries(headers).map(([k, v]) => [k.toLowerCase(), v]));

/** The label of one response, with the vendor and the rule that decided it. */
export function classify({ status, headers = {}, body = "" }) {
  const h = lower(headers);
  for (const [name, re, vendor] of CHALLENGE_HEADERS) {
    if (re.test(String(h[name] ?? ""))) return { label: "challenge", vendor, rule: `header:${name}` };
  }
  const text = String(body);
  for (const [re, vendor] of CHALLENGE_BODIES) if (re.test(text)) return { label: "challenge", vendor, rule: "body" };
  for (const [re, vendor] of BLOCK_BODIES) if (re.test(text)) return { label: "block", vendor, rule: "body" };
  if (status >= 400) return { label: "origin-error", vendor: null, rule: "status" };
  return { label: "page", vendor: null, rule: "status" };
}

/** Cookie names only, never values. */
export function cookieNames(headers = {}) {
  const raw = lower(headers)["set-cookie"];
  const list = Array.isArray(raw) ? raw : raw ? [raw] : [];
  return list.map((c) => String(c).split("=")[0].trim()).filter(Boolean).sort();
}

// § 6, secondary: what kind of site this is, from the homepage already fetched.
// Fixed rules on the HTML; only the booleans are kept, never a URL or a name.
export const TRAIT_RULES = Object.freeze({
  login: /<a\b[^>]*>\s*(?:<[^>]+>\s*)*(log\s?in|sign\s?in|my account|inloggen|anmelden|connexion)\b/i,
  payments: /js\.stripe\.com|checkout\.stripe\.com|paypal\.com\/sdk|paypalobjects\.com|js\.braintreegateway\.com|checkoutshopper-[a-z]+\.adyen\.com|klarna(?:cdn|\.com)|mollie\.com/i,
  shop: /cdn\.shopify\.com|woocommerce|magento|\/cart\b|\/checkout\b|add[-_ ]to[-_ ]cart/i,
  // A public security or trust page: a stand-in for a team that owns security, not proof of a CISO.
  securityPage: /<a\b[^>]*href="[^"]*(?:\/security\b|\/trust\b|\/trust-center|\/\/trust\.|\/\/security\.)[^"]*"/i,
});

/** Booleans for one page. An empty page (no 2xx HTML) gives null: unknown, not "no". */
export function traitsOf(html) {
  if (!html) return null;
  return Object.fromEntries(Object.entries(TRAIT_RULES).map(([k, re]) => [k, re.test(html)]));
}

const headerEvidence = (res) => {
  const h = lower(res.headers);
  return {
    status: res.status,
    headerNames: Object.keys(h).sort(),
    values: Object.fromEntries(KEPT_VALUES.filter((k) => h[k] !== undefined).map((k) => [k, String(h[k]).slice(0, 120)])),
    cookieNames: cookieNames(h),
  };
};

const redactEmails = (s) => s.replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g, "<redacted>");

/**
 * What E20-R stores for one site (§ 4.1). The body of a 2xx page is hashed and
 * never kept; a response outside 2xx keeps its first 4 KB, emails redacted.
 */
export function evidenceOf(page, responses = []) {
  const body = String(page.body ?? "");
  const outside2xx = page.status < 200 || page.status >= 300;
  return {
    ...headerEvidence(page),
    bodySha256: createHash("sha256").update(body).digest("hex"),
    ...(outside2xx ? { excerpt: redactEmails(body.slice(0, EXCERPT_BYTES)) } : {}),
    class: classify(page),
    traits: traitsOf(page.html),
    others: responses.map(({ kind, res }) => ({ kind, ...headerEvidence(res) })),
  };
}
